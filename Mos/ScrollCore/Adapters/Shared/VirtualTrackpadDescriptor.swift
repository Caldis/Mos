//  Mos
//  虚拟 Magic Trackpad 2 的报文描述符与特性报文握手应答
//
//  致谢: 报文描述符与特性报文握手应答取自 acidanthera/VoodooInput 的 VoodooInputSimulatorDevice
//  (https://github.com/acidanthera/VoodooInput)。
//  设备以 VendorID 0x05AC, ProductID 0x0281, I2C 传输发布后由 AppleMultitouchTrackpadHIDEventDriver 接管:
//  驱动先 SET 报文 1 写入查询字节, 再 GET 读取应答 (设备族 ID, 传感器行列数, 表面尺寸),
//  最后 SET 报文 2 = 02 01 开启多点触控模式, 随后注册表中出现 AppleMultitouchDevice
//

import Foundation
import os
#if canImport(CoreHID)
import CoreHID
#endif

enum VirtualTrackpadDescriptor {

    static let serialNumber = "Mos Scroll Identity"
    /// ASCII "Mos!"
    static let locationID: UInt64 = 0x4D6F_7321

    static let reportDescriptor: [UInt8] = [
        0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x85, 0x02, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31,
        0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0x95, 0x04, 0x75, 0x08, 0x81, 0x01, 0xc0, 0xc0, 0x05, 0x0d,
        0x09, 0x05, 0xa1, 0x01, 0x06, 0x00, 0xff, 0x09, 0x0c, 0x15, 0x00, 0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x10, 0x85, 0x3f,
        0x81, 0x22, 0xc0, 0x06, 0x00, 0xff, 0x09, 0x0c, 0xa1, 0x01, 0x06, 0x00, 0xff, 0x09, 0x0c, 0x15, 0x00, 0x26, 0xff, 0x00,
        0x85, 0x44, 0x75, 0x08, 0x96, 0x6b, 0x05, 0x81, 0x00, 0xc0,
    ]

    /// 传感器表面 156.00 x 110.40 mm, 单位 0.01 mm
    static let surface: [UInt8] = [0xD9, 0xF0, 0x3C, 0x00, 0x00, 0x20, 0x2B, 0x00, 0x00, 0x44, 0xE3, 0x52, 0xFF, 0xBD, 0x1E, 0xE4, 0x26]

    /// SET 报文 1 的查询字节对应的应答
    static func setReply(for command: UInt8) -> [UInt8] {
        switch command {
        case 0xDB: return [0x01, 0xDB, 0x00, 0x49, 0x00]
        case 0xD1: return [0x01, 0xD1, 0x00, 0x01, 0x00]
        case 0xD3: return [0x01, 0xD3, 0x00, 0x0C, 0x00]
        case 0xD0: return [0x01, 0xD0, 0x00, 0x0F, 0x00]
        case 0xA1: return [0x01, 0xA1, 0x00, 0x06, 0x00]
        case 0xD9: return surface
        case 0x7F: return [0x01, 0x7F, 0x00, 0x04, 0x00]
        case 0xC8: return [0x01, 0xC8, 0x00, 0x01, 0x00]
        default: return []
        }
    }

    /// GET 报文的应答; 报文 1 返回最近一次 SET 选择的查询项
    static func getReply(for reportID: UInt8, pending: [UInt8]) -> [UInt8] {
        switch reportID {
        case 0x00: return [0x00, 0x01]
        case 0x01: return pending
        case 0xD1: return [0xD1, 0x81]
        case 0xD3: return [0xD3, 0x01, 0x16, 0x1E, 0x03, 0x95, 0x00, 0x14, 0x1E, 0x62, 0x05, 0x00, 0x00]
        case 0xD0: return [0xD0, 0x02, 0x01, 0x00, 0x14, 0x01, 0x00, 0x1E, 0x00, 0x02, 0x14, 0x02, 0x01, 0x0E, 0x02, 0x00]
        case 0xA1: return [0xA1, 0x00, 0x00, 0x05, 0x00, 0xFC, 0x01]
        case 0xD9: return surface
        case 0x7F: return [0x7F, 0x00, 0x00, 0x00, 0x00]
        case 0xC8: return [0xC8, 0x08]
        case 0x02: return [0x02, 0x01]
        case 0xDB:
            return [0xDB, 0x01, 0x02, 0x00, 0xD1, 0x81, 0x0D, 0x00,
                    0xD3, 0x01, 0x16, 0x1E, 0x03, 0x95, 0x00, 0x14, 0x1E, 0x62, 0x05, 0x00, 0x00, 0x10, 0x00,
                    0xD0, 0x02, 0x01, 0x00, 0x14, 0x01, 0x00, 0x1E, 0x00, 0x02, 0x14, 0x02, 0x01, 0x0E, 0x02, 0x00, 0x07, 0x00,
                    0xA1, 0x00, 0x00, 0x05, 0x00, 0xFC, 0x01, 0x11, 0x00] + surface + [0x7F, 0x00, 0x00, 0x00, 0x00]
        default: return []
        }
    }

    /// SET 报文的查询字节: 报文 ID 为 1 时取首字节, 否则取 [0x01, 查询字节] 中的第二字节
    static func command(reportID: UInt8?, data: [UInt8]) -> UInt8? {
        guard reportID == 0x01 || data.first == 0x01 else { return nil }
        if data.first == 0x01 && data.count > 1 { return data[1] }
        return data.first
    }

    #if canImport(CoreHID)
    @available(macOS 15.0, *)
    static var properties: HIDVirtualDevice.Properties {
        return HIDVirtualDevice.Properties(
            descriptor: Data(reportDescriptor),
            vendorID: 0x05AC,
            productID: 0x0281,
            transport: .i2c,
            product: "Magic Trackpad 2",
            manufacturer: "Apple Inc.",
            versionNumber: 0x804,
            serialNumber: serialNumber,
            locationID: locationID
        )
    }

    @available(macOS 15.0, *)
    final class Delegate: HIDVirtualDeviceDelegate {
        private var lock = os_unfair_lock_s()
        private var pending: [UInt8] = []

        func hidVirtualDevice(_ device: HIDVirtualDevice, receivedSetReportRequestOfType type: HIDReportType,
                              id: HIDReportID?, data: Data) async throws {
            guard let command = VirtualTrackpadDescriptor.command(reportID: id?.rawValue, data: [UInt8](data)) else { return }
            let reply = VirtualTrackpadDescriptor.setReply(for: command)
            os_unfair_lock_lock(&lock)
            pending = reply
            os_unfair_lock_unlock(&lock)
        }

        func hidVirtualDevice(_ device: HIDVirtualDevice, receivedGetReportRequestOfType type: HIDReportType,
                              id: HIDReportID?, maxSize: Int) async throws -> Data {
            os_unfair_lock_lock(&lock)
            let current = pending
            os_unfair_lock_unlock(&lock)
            return Data(VirtualTrackpadDescriptor.getReply(for: id?.rawValue ?? 0, pending: current).prefix(maxSize))
        }
    }
    #endif
}
